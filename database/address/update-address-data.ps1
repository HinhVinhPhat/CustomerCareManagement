<#
.SYNOPSIS
    Refreshes the Vietnamese administrative data used by the customer address form.

.DESCRIPTION
    Downloads the two-level catalogue (province/city + ward/commune) from
    provinces.open-api.vn (API v2) ONCE, saves the raw JSON next to this script and regenerates
    database/05_AddressData.sql. The application never calls the external API at run time: it reads
    the tables filled by that SQL file.

    Run this script every few months, or when the Government announces a change:
        powershell -ExecutionPolicy Bypass -File database/address/update-address-data.ps1
    Then commit both vn-provinces.json and 05_AddressData.sql.

    Rows that disappeared from the API are kept but marked IsActive = 0, so old customers that
    still point at them keep a readable address (AGENTS.md: never delete old address data).

.PARAMETER Uri
    Override the source URL (useful for testing with a saved file or a mirror).

.PARAMETER SkipDownload
    Regenerate the SQL file from the JSON already stored on disk (no network call).
#>
[CmdletBinding()]
param(
    [string] $Uri = 'https://provinces.open-api.vn/api/v2/?depth=2',
    [switch] $SkipDownload
)

$ErrorActionPreference = 'Stop'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$databaseDir = Split-Path -Parent $PSScriptRoot
$jsonPath = Join-Path $PSScriptRoot 'vn-provinces.json'
$sqlPath = Join-Path $databaseDir '05_AddressData.sql'

if (-not $SkipDownload) {
    Write-Host "Downloading $Uri ..."
    $ProgressPreference = 'SilentlyContinue'
    Invoke-WebRequest -Uri $Uri -OutFile $jsonPath -UseBasicParsing
}

$json = [IO.File]::ReadAllText($jsonPath, [Text.Encoding]::UTF8)
$provinces = $json | ConvertFrom-Json

if ($provinces.Count -lt 30) {
    throw "Only $($provinces.Count) provinces came back - refusing to overwrite good data."
}

$wardCount = 0
foreach ($province in $provinces) {
    if ($province.code -le 0 -or [string]::IsNullOrWhiteSpace($province.name)) {
        throw 'A province row is missing its code or name.'
    }

    foreach ($ward in $province.wards) {
        if ($ward.code -le 0 -or [string]::IsNullOrWhiteSpace($ward.name)) {
            throw "A ward of $($province.name) is missing its code or name."
        }
        # The full catalogue omits province_code on a ward (it is implied by the parent), while
        # /p/{code}?depth=2 includes it. Only trust the field when it is actually present.
        if ($null -ne $ward.PSObject.Properties['province_code'] -and
            $ward.province_code -and
            $ward.province_code -ne $province.code) {
            throw "Ward $($ward.code) claims province $($ward.province_code), expected $($province.code)."
        }
        $wardCount++
    }
}

if ($wardCount -lt 3000) {
    throw "Only $wardCount wards came back - refusing to overwrite good data."
}

function ConvertTo-SqlString([string] $value) {
    return "N'" + $value.Replace("'", "''") + "'"
}

$out = New-Object System.Text.StringBuilder
$null = $out.AppendLine('/* =====================================================================')
$null = $out.AppendLine('   CUSTOMER CARE MANAGEMENT SYSTEM  -  VERSION 2')
$null = $out.AppendLine('   File 5: Vietnamese administrative catalogue (province/city + ward/commune).')
$null = $out.AppendLine('   AUTO-GENERATED by database/address/update-address-data.ps1 - do not edit by hand.')
$null = $out.AppendLine("   Source: provinces.open-api.vn API v2, downloaded $(Get-Date -Format 'yyyy-MM-dd').")
$null = $out.AppendLine('   Rows removed from the source are kept with IsActive = 0 so old addresses stay readable.')
$null = $out.AppendLine('   Safe to run repeatedly: the schema is created only when missing and rows are merged.')
$null = $out.AppendLine('   ===================================================================== */')
$null = $out.AppendLine('USE CustomerCareDB;')
$null = $out.AppendLine('GO')
$null = $out.AppendLine('')
$null = $out.AppendLine('-- Schema for a database created before the address catalogue existed.')
$null = $out.AppendLine("IF OBJECT_ID(N'dbo.PROVINCE', N'U') IS NULL")
$null = $out.AppendLine('BEGIN')
$null = $out.AppendLine('    CREATE TABLE dbo.PROVINCE (')
$null = $out.AppendLine('        ProvinceCode  INT NOT NULL PRIMARY KEY,')
$null = $out.AppendLine('        ProvinceName  NVARCHAR(100) NOT NULL,')
$null = $out.AppendLine('        DivisionType  NVARCHAR(50) NOT NULL,')
$null = $out.AppendLine('        IsActive      BIT NOT NULL DEFAULT 1')
$null = $out.AppendLine('    );')
$null = $out.AppendLine('END')
$null = $out.AppendLine('GO')
$null = $out.AppendLine('')
$null = $out.AppendLine("IF OBJECT_ID(N'dbo.WARD', N'U') IS NULL")
$null = $out.AppendLine('BEGIN')
$null = $out.AppendLine('    CREATE TABLE dbo.WARD (')
$null = $out.AppendLine('        WardCode      INT NOT NULL PRIMARY KEY,')
$null = $out.AppendLine('        ProvinceCode  INT NOT NULL,')
$null = $out.AppendLine('        WardName      NVARCHAR(100) NOT NULL,')
$null = $out.AppendLine('        DivisionType  NVARCHAR(50) NOT NULL,')
$null = $out.AppendLine('        IsActive      BIT NOT NULL DEFAULT 1,')
$null = $out.AppendLine('        CONSTRAINT FK_Ward_Province FOREIGN KEY (ProvinceCode) REFERENCES dbo.PROVINCE(ProvinceCode)')
$null = $out.AppendLine('    );')
$null = $out.AppendLine('    CREATE INDEX IX_Ward_Province ON dbo.WARD(ProvinceCode);')
$null = $out.AppendLine('END')
$null = $out.AppendLine('GO')
$null = $out.AppendLine('')
$null = $out.AppendLine("IF COL_LENGTH(N'dbo.CUSTOMER', N'ProvinceCode') IS NULL")
$null = $out.AppendLine('    ALTER TABLE dbo.CUSTOMER ADD ProvinceCode INT NULL;')
$null = $out.AppendLine('GO')
$null = $out.AppendLine("IF COL_LENGTH(N'dbo.CUSTOMER', N'WardCode') IS NULL")
$null = $out.AppendLine('    ALTER TABLE dbo.CUSTOMER ADD WardCode INT NULL;')
$null = $out.AppendLine('GO')
$null = $out.AppendLine("IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_Customer_Province')")
$null = $out.AppendLine('    ALTER TABLE dbo.CUSTOMER ADD CONSTRAINT FK_Customer_Province')
$null = $out.AppendLine('        FOREIGN KEY (ProvinceCode) REFERENCES dbo.PROVINCE(ProvinceCode);')
$null = $out.AppendLine('GO')
$null = $out.AppendLine("IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_Customer_Ward')")
$null = $out.AppendLine('    ALTER TABLE dbo.CUSTOMER ADD CONSTRAINT FK_Customer_Ward')
$null = $out.AppendLine('        FOREIGN KEY (WardCode) REFERENCES dbo.WARD(WardCode);')
$null = $out.AppendLine('GO')
$null = $out.AppendLine('')
$null = $out.AppendLine('-- Mark everything stale first; the MERGE below switches the current rows back on.')
$null = $out.AppendLine('UPDATE dbo.WARD SET IsActive = 0;')
$null = $out.AppendLine('UPDATE dbo.PROVINCE SET IsActive = 0;')
$null = $out.AppendLine('GO')
$null = $out.AppendLine('')
$null = $out.AppendLine('MERGE dbo.PROVINCE AS target')
$null = $out.AppendLine('USING (VALUES')
$rows = @()
foreach ($province in $provinces) {
    $rows += '    (' + $province.code + ', ' + (ConvertTo-SqlString $province.name) + ', ' + (ConvertTo-SqlString $province.division_type) + ')'
}
$null = $out.AppendLine(($rows -join ",`r`n"))
$null = $out.AppendLine(') AS source (ProvinceCode, ProvinceName, DivisionType)')
$null = $out.AppendLine('ON target.ProvinceCode = source.ProvinceCode')
$null = $out.AppendLine('WHEN MATCHED THEN UPDATE SET ProvinceName = source.ProvinceName,')
$null = $out.AppendLine('                              DivisionType = source.DivisionType,')
$null = $out.AppendLine('                              IsActive = 1')
$null = $out.AppendLine('WHEN NOT MATCHED THEN INSERT (ProvinceCode, ProvinceName, DivisionType, IsActive)')
$null = $out.AppendLine('                      VALUES (source.ProvinceCode, source.ProvinceName, source.DivisionType, 1);')
$null = $out.AppendLine('GO')
$null = $out.AppendLine('')

# A MERGE table-value constructor accepts at most 1000 rows, so wards go in batches.
$wardRows = @()
foreach ($province in $provinces) {
    foreach ($ward in $province.wards) {
        $wardRows += '    (' + $ward.code + ', ' + $province.code + ', ' + (ConvertTo-SqlString $ward.name) + ', ' + (ConvertTo-SqlString $ward.division_type) + ')'
    }
}

$batchSize = 500
for ($start = 0; $start -lt $wardRows.Count; $start += $batchSize) {
    $end = [Math]::Min($start + $batchSize - 1, $wardRows.Count - 1)
    $batch = $wardRows[$start..$end]

    $null = $out.AppendLine('MERGE dbo.WARD AS target')
    $null = $out.AppendLine('USING (VALUES')
    $null = $out.AppendLine(($batch -join ",`r`n"))
    $null = $out.AppendLine(') AS source (WardCode, ProvinceCode, WardName, DivisionType)')
    $null = $out.AppendLine('ON target.WardCode = source.WardCode')
    $null = $out.AppendLine('WHEN MATCHED THEN UPDATE SET ProvinceCode = source.ProvinceCode,')
    $null = $out.AppendLine('                              WardName = source.WardName,')
    $null = $out.AppendLine('                              DivisionType = source.DivisionType,')
    $null = $out.AppendLine('                              IsActive = 1')
    $null = $out.AppendLine('WHEN NOT MATCHED THEN INSERT (WardCode, ProvinceCode, WardName, DivisionType, IsActive)')
    $null = $out.AppendLine('                      VALUES (source.WardCode, source.ProvinceCode, source.WardName, source.DivisionType, 1);')
    $null = $out.AppendLine('GO')
    $null = $out.AppendLine('')
}

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText($sqlPath, $out.ToString(), $utf8NoBom)

Write-Host "OK: $($provinces.Count) provinces, $wardCount wards -> $sqlPath"
